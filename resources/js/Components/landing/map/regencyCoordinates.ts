/**
 * Mendapatkan koordinat [lat, lng] untuk suatu kabupaten/kota.
 * Jika nama daerah spesifik tidak ditemukan, otomatis fallback ke koordinat daratan provinsi.
 */
export function getRegencyCoordinates(
  regencyName: string,
  provinceId?: string
): [number, number] | null {
  if (!regencyName) {
    return provinceId && PROVINCE_LAND_COORDINATES[provinceId]
      ? PROVINCE_LAND_COORDINATES[provinceId]
      : null;
  }

  const cleanKey = normalizeRegencyKey(regencyName);

  // 1. Cek langsung dengan key yang dinormalisasi
  if (REGENCY_COORDINATES[cleanKey]) {
    return REGENCY_COORDINATES[cleanKey];
  }

  // 2. Cek dengan variasi prefix kota- atau kab-
  if (REGENCY_COORDINATES['kota-' + cleanKey]) {
    return REGENCY_COORDINATES['kota-' + cleanKey];
  }
  if (REGENCY_COORDINATES['kab-' + cleanKey]) {
    return REGENCY_COORDINATES['kab-' + cleanKey];
  }

  // 3. Cek dengan gabungan provinceId-cleanKey jika ada
  if (provinceId && REGENCY_COORDINATES[provinceId + '-' + cleanKey]) {
    return REGENCY_COORDINATES[provinceId + '-' + cleanKey];
  }

  // 4. Fallback ke koordinat daratan provinsi jika tersedia
  if (provinceId && PROVINCE_LAND_COORDINATES[provinceId]) {
    return PROVINCE_LAND_COORDINATES[provinceId];
  }

  return null;
}
