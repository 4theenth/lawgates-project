/**
 * Normalisasi nama kabupaten/kota untuk pencarian key koordinat.
 * Contoh: "Kabupaten Badung" -> "badung", "Kota Bandung" -> "bandung"
 */
export function normalizeRegencyKey(name: string): string {
  return name
    .toLowerCase()
    .replace(/^(pemerintah\s+daerah|pemerintah\s+kabupaten|pemerintah\s+kota|pemerintah|kabupaten|kab\.|kota|adm\.|administrasi)\s+/i, '')
    .trim()
    .replace(/[^a-z0-9]/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '');
}

