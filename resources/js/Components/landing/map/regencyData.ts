/**
 * Pemetaan nama kabupaten/kota ke slug provinsi.
 */
export function findProvinceIdForRegency(regencyName: string): string | null {
  const clean = regencyName
    .toLowerCase()
    .replace(/^(pemerintah\s+daerah|pemerintah\s+kabupaten|pemerintah\s+kota|pemerintah|kabupaten|kab\.|kota)\s+/i, '')
    .trim();

  for (const prov of Object.values(PROVINCE_REGENCY_MAP)) {
    for (const reg of prov.regencies) {
      if (reg.name.toLowerCase() === clean) {
        return prov.provinceId;
      }
    }
  }
  return null;
}

/**
 * Ekstraksi nama dan normalized key provinsi dari string lokasi
 */
export function extractProvinceName(rawName: string): { key: string; name: string } {
  const cleaned = rawName
    .replace(/^pemerintah\s+provinsi\s+/i, '')
    .replace(/^provinsi\s+/i, '')
    .trim();
  const key = cleaned
    .toLowerCase()
    .replace(/^daerah istimewa yogyakarta$/, 'di-yogyakarta')
    .replace(/^dki jakarta$/, 'dki-jakarta')
    .replace(/[^a-z0-9]/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '');
  return { key, name: cleaned || rawName };
}

/**
 * Mengambil data kabupaten/kota resmi untuk provinsi tertentu.
 */
export function getRegenciesForProvince(
  provinceId: string,
  provinceName: string
): ProvinceRegencyData {
  const normalizedId = provinceId.toLowerCase().trim();
  if (PROVINCE_REGENCY_MAP[normalizedId]) {
    return PROVINCE_REGENCY_MAP[normalizedId];
  }

  const formattedName = provinceName.trim() || 'Wilayah';
  return {
    provinceId: normalizedId,
    provinceName: formattedName,
    kabupatenCount: 0,
    kotaCount: 0,
    totalCount: 0,
    regencies: [],
  };
}
